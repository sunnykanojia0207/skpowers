#!/usr/bin/env python3
"""Generate each AI coding tool's config from the toolkit's single sources.

Sources (edit these):
  AGENTS.md            rules, read natively by most tools
  .agents/skills/      your own skills, read natively by most tools
  toolkit.config.json  tools you use, skill profiles to enable, MCP servers
  skills-library/      vendored third-party skills (update with vendor_skills.py)

Outputs (never edit by hand): enabled library skills copied into .agents/skills/,
per-tool MCP config files, and the Claude Code skill mirror. Existing MCP files
are merged: only server names defined in toolkit.config.json are replaced, so
servers you added yourself are kept.

Usage:
  python scripts/sync_toolkit.py           write outputs
  python scripts/sync_toolkit.py --check   exit 1 if any output is stale
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG_FILE = "toolkit.config.json"
LIBRARY_CATALOG = Path("skills-library") / "library.json"
KNOWN_TOOLS = {"claude-code", "codex", "cursor", "opencode", "gemini-cli", "antigravity", "copilot"}
NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
ENV_NAME_RE = re.compile(r"^[A-Z_][A-Z0-9_]*$")
PLACEHOLDER_RE = re.compile(r"YOUR_[A-Z_]+")
MIRROR_MARKER = ".toolkit-generated"
TOML_BEGIN = "# >>> vibe-toolkit MCP servers: generated by scripts/sync_toolkit.py, edit toolkit.config.json >>>"
TOML_END = "# <<< vibe-toolkit MCP servers <<<"


class SyncError(Exception):
    pass


# ---------------------------------------------------------------- config

def load_config(root: Path) -> dict:
    path = root / CONFIG_FILE
    try:
        config = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SyncError(f"Cannot read {CONFIG_FILE}: {exc}") from exc

    tools = config.get("tools")
    if not isinstance(tools, list) or not all(isinstance(t, str) for t in tools):
        raise SyncError(f"{CONFIG_FILE}: 'tools' must be a list of strings")
    unknown = sorted(set(tools) - KNOWN_TOOLS)
    if unknown:
        raise SyncError(f"{CONFIG_FILE}: unknown tools {unknown}; known: {sorted(KNOWN_TOOLS)}")

    for key in ("skillProfiles", "skills"):
        value = config.setdefault(key, [])
        if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
            raise SyncError(f"{CONFIG_FILE}: '{key}' must be a list of strings")

    servers = config.get("mcpServers")
    if not isinstance(servers, dict):
        raise SyncError(f"{CONFIG_FILE}: 'mcpServers' must be an object")
    for name, server in servers.items():
        validate_server(name, server)
    return config


def resolve_library_skills(root: Path, config: dict) -> dict[str, Path]:
    """Map each enabled library skill name to its vendored folder."""
    wanted = config["skillProfiles"] or config["skills"]
    if not wanted:
        return {}
    path = root / LIBRARY_CATALOG
    try:
        catalog = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SyncError(f"Cannot read {LIBRARY_CATALOG.as_posix()}: {exc}") from exc

    locations = {
        skill: root / "skills-library" / source_name / skill
        for source_name, source in catalog["sources"].items()
        for skill in source["skills"]
    }
    profiles = catalog["profiles"]
    names: list[str] = []
    for profile in config["skillProfiles"]:
        if profile not in profiles:
            raise SyncError(f"{CONFIG_FILE}: unknown skill profile {profile!r}; available: {sorted(profiles)}")
        names += profiles[profile]["skills"]
    names += config["skills"]

    enabled: dict[str, Path] = {}
    for name in names:
        if name not in locations:
            raise SyncError(f"{CONFIG_FILE}: skill {name!r} is not in {LIBRARY_CATALOG.as_posix()}")
        if not (locations[name] / "SKILL.md").is_file():
            raise SyncError(f"{name!r} is not vendored yet; run: python scripts/vendor_skills.py")
        enabled[name] = locations[name]
    return enabled


def validate_server(name: str, server: object) -> None:
    where = f"{CONFIG_FILE}: server {name!r}"
    if not NAME_RE.fullmatch(name):
        raise SyncError(f"{where}: name must be lowercase letters, digits and single hyphens")
    if not isinstance(server, dict):
        raise SyncError(f"{where}: must be an object")
    if not isinstance(server.get("enabled"), bool):
        raise SyncError(f"{where}: 'enabled' must be true or false")
    transport = server.get("transport")
    if transport == "stdio":
        if not isinstance(server.get("command"), str) or not server["command"]:
            raise SyncError(f"{where}: stdio servers need a 'command'")
        args = server.get("args", [])
        if not isinstance(args, list) or not all(isinstance(a, str) for a in args):
            raise SyncError(f"{where}: 'args' must be a list of strings")
        passthrough = server.get("envPassthrough", [])
        if not isinstance(passthrough, list) or not all(isinstance(n, str) and ENV_NAME_RE.fullmatch(n) for n in passthrough):
            raise SyncError(f"{where}: 'envPassthrough' must be a list of UPPER_CASE variable names")
        static = server.get("env", {})
        if not isinstance(static, dict) or not all(
            isinstance(k, str) and ENV_NAME_RE.fullmatch(k) and isinstance(v, str) for k, v in static.items()
        ):
            raise SyncError(f"{where}: 'env' must map UPPER_CASE names to non-secret string values")
        if set(static) & set(passthrough):
            raise SyncError(f"{where}: a variable cannot be in both 'env' and 'envPassthrough'")
    elif transport == "http":
        if not isinstance(server.get("url"), str) or not server["url"].startswith("https://"):
            raise SyncError(f"{where}: http servers need an https 'url'")
    else:
        raise SyncError(f"{where}: 'transport' must be 'stdio' or 'http'")
    placeholder = PLACEHOLDER_RE.search(json.dumps(server))
    if server["enabled"] and placeholder:
        raise SyncError(f"{where}: replace the {placeholder.group(0)} placeholder before enabling it")


# ---------------------------------------------------------------- per-tool MCP entries
# Each renderer maps one canonical server to that tool's documented schema.

def env_map(server: dict, template: str) -> dict:
    """Fixed non-secret values plus secret references in the tool's own syntax."""
    passthrough = {name: template.format(name=name) for name in server.get("envPassthrough", [])}
    return {**server.get("env", {}), **passthrough}


def claude_entry(server: dict) -> dict:
    # Claude Code .mcp.json; also the portable workspace file read by VS Code / Copilot.
    if server["transport"] == "http":
        return {"type": "http", "url": server["url"]}
    entry = {"type": "stdio", "command": server["command"], "args": server.get("args", [])}
    if env := env_map(server, "${{{name}}}"):
        entry["env"] = env
    return entry


def cursor_entry(server: dict) -> dict:
    if server["transport"] == "http":
        return {"url": server["url"]}
    entry = {"type": "stdio", "command": server["command"], "args": server.get("args", [])}
    if env := env_map(server, "${{env:{name}}}"):
        entry["env"] = env
    return entry


def opencode_entry(server: dict) -> dict:
    if server["transport"] == "http":
        return {"type": "remote", "url": server["url"], "enabled": True}
    entry = {"type": "local", "command": [server["command"], *server.get("args", [])], "enabled": True}
    if env := env_map(server, "{{env:{name}}}"):
        entry["environment"] = env
    return entry


def gemini_entry(server: dict) -> dict:
    if server["transport"] == "http":
        return {"httpUrl": server["url"]}
    entry = {"command": server["command"], "args": server.get("args", [])}
    if env := env_map(server, "${{{name}}}"):
        entry["env"] = env
    return entry


def antigravity_entry(server: dict) -> dict:
    # Antigravity documents no env interpolation, so passthrough variables are
    # inherited from the launching shell instead of written into the file.
    if server["transport"] == "http":
        return {"serverUrl": server["url"]}
    entry = {"command": server["command"], "args": server.get("args", [])}
    if server.get("env"):
        entry["env"] = dict(server["env"])
    return entry


# (tools that need the file, path, container key, renderer, top-level defaults)
JSON_TARGETS = [
    ({"claude-code", "copilot"}, ".mcp.json", "mcpServers", claude_entry, {}),
    ({"cursor"}, ".cursor/mcp.json", "mcpServers", cursor_entry, {}),
    ({"opencode"}, "opencode.json", "mcp", opencode_entry, {"$schema": "https://opencode.ai/config.json"}),
    ({"gemini-cli"}, ".gemini/settings.json", "mcpServers", gemini_entry, {}),
    ({"antigravity"}, ".agents/mcp_config.json", "mcpServers", antigravity_entry, {}),
]


def read_text(path: Path) -> str | None:
    if not path.exists():
        return None
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def render_json_target(path: Path, key: str, renderer, defaults: dict, servers: dict) -> str:
    current = read_text(path)
    try:
        existing = json.loads(current) if current else {}
    except json.JSONDecodeError as exc:
        raise SyncError(f"{path}: not valid JSON ({exc}); fix it before syncing") from exc
    if not isinstance(existing, dict) or not isinstance(existing.get(key, {}), dict):
        raise SyncError(f"{path}: expected a JSON object with an object '{key}'")

    result = {**defaults, **existing}
    managed = {name: renderer(s) for name, s in servers.items() if s["enabled"]}
    kept = {name: v for name, v in existing.get(key, {}).items() if name not in servers}
    result[key] = {**managed, **kept}
    return json.dumps(result, indent=2, ensure_ascii=False) + "\n"


def toml_value(value) -> str:
    # JSON string and array syntax is valid TOML for plain strings.
    return json.dumps(value, ensure_ascii=False)


def render_codex(path: Path, servers: dict) -> str:
    lines = [TOML_BEGIN]
    for name, server in servers.items():
        if not server["enabled"]:
            continue
        lines += ["", f"[mcp_servers.{name}]"]
        if server["transport"] == "http":
            lines.append(f"url = {toml_value(server['url'])}")
        else:
            lines.append(f"command = {toml_value(server['command'])}")
            lines.append(f"args = {toml_value(server.get('args', []))}")
            if server.get("envPassthrough"):
                lines.append(f"env_vars = {toml_value(server['envPassthrough'])}")
            if server.get("env"):
                pairs = ", ".join(f"{k} = {toml_value(v)}" for k, v in server["env"].items())
                lines.append(f"env = {{ {pairs} }}")
    lines += ["", TOML_END]
    block = "\n".join(lines)

    current = read_text(path) or ""
    start = current.find(TOML_BEGIN)
    if start >= 0:
        end = current.find(TOML_END, start)
        if end < 0:
            raise SyncError(f"{path}: generated block start marker has no end marker")
        return current[:start] + block + current[end + len(TOML_END):]

    for name in servers:
        if re.search(rf"^\s*\[mcp_servers\.\"?{re.escape(name)}\"?[\].]", current, re.MULTILINE):
            raise SyncError(f"{path}: [mcp_servers.{name}] is defined by hand; remove it or rename it")
    prefix = current.rstrip("\n") + "\n\n" if current.strip() else ""
    return prefix + block + "\n"


# ---------------------------------------------------------------- generated skill folders
# Library skills are copied into .agents/skills/, and everything in .agents/skills/
# is mirrored into .claude/skills/. Generated folders carry MIRROR_MARKER, so
# hand-written skills are never overwritten or removed.

Action = tuple[str, Path, "Path | None"]


def tree_bytes(directory: Path) -> dict[str, bytes]:
    return {
        p.relative_to(directory).as_posix(): p.read_bytes().replace(b"\r\n", b"\n")
        for p in sorted(directory.rglob("*"))
        if p.is_file()
    }


def plan_copies(sources: dict[str, Path], dest_root: Path) -> list[Action]:
    """Return ('copy' | 'remove', target, source) actions that make dest_root match sources."""
    actions: list[Action] = []
    for name, source in sources.items():
        target = dest_root / name
        if target.exists() and not (target / MIRROR_MARKER).exists():
            raise SyncError(f"{target} exists and was not generated; rename one of the two '{name}' skills")
        expected = {**tree_bytes(source), MIRROR_MARKER: b""}
        if not target.exists() or tree_bytes(target) != expected:
            actions.append(("copy", target, source))

    if dest_root.is_dir():
        for target in sorted(dest_root.iterdir()):
            if (target / MIRROR_MARKER).exists() and target.name not in sources:
                actions.append(("remove", target, None))
    return actions


def plan_skill_mirror(root: Path, enabled: bool) -> list[Action]:
    source_root = root / ".agents" / "skills"
    sources = {p.parent.name: p.parent for p in sorted(source_root.glob("*/SKILL.md"))} if enabled else {}
    return plan_copies(sources, root / ".claude" / "skills")


def apply_copies(actions: list[Action]) -> None:
    for action, target, source in actions:
        if target.exists():
            shutil.rmtree(target)
        if action == "copy" and source is not None:
            shutil.copytree(source, target)
            (target / MIRROR_MARKER).write_bytes(b"")


# ---------------------------------------------------------------- main

def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report stale outputs without writing; exit 1 if any")
    args = parser.parse_args(argv)

    try:
        config = load_config(ROOT)
        tools = set(config["tools"])
        servers = config["mcpServers"]

        files: dict[Path, str] = {}
        for needed_by, rel, key, renderer, defaults in JSON_TARGETS:
            if tools & needed_by:
                files[ROOT / rel] = render_json_target(ROOT / rel, key, renderer, defaults, servers)
        if "codex" in tools:
            files[ROOT / ".codex" / "config.toml"] = render_codex(ROOT / ".codex" / "config.toml", servers)
        library_skills = resolve_library_skills(ROOT, config)
        library_actions = plan_copies(library_skills, ROOT / ".agents" / "skills")
        if not args.check:
            apply_copies(library_actions)  # the mirror below must see the new library skills
        mirror_actions = plan_skill_mirror(ROOT, "claude-code" in tools)
    except SyncError as exc:
        print(f"sync_toolkit: {exc}", file=sys.stderr)
        return 2

    def describe(actions: list[Action]) -> list[str]:
        return [f"{t.relative_to(ROOT).as_posix()}/ ({action})" for action, t, _ in actions]

    stale_files = [path for path, text in files.items() if read_text(path) != text]
    stale = [p.relative_to(ROOT).as_posix() for p in stale_files] + describe(library_actions) + describe(mirror_actions)
    summary = f"{len(files)} config files, {len(library_skills)} library skills, tools: {', '.join(sorted(tools))}"

    if args.check:
        if stale:
            print("Toolkit outputs are stale; run: python scripts/sync_toolkit.py")
            for item in stale:
                print(f"- {item}")
            return 1
        print(f"Toolkit outputs are up to date ({summary}).")
        return 0

    for path in stale_files:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[path], encoding="utf-8", newline="\n")
    apply_copies(mirror_actions)

    print(f"Updated ({summary}):" if stale else f"Nothing to update ({summary}).")
    for item in stale:
        print(f"- {item}")
    if "codex" in tools:
        print("Note: Codex reads .codex/config.toml only after you mark this project as trusted.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
